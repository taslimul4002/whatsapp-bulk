    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        foreach (self::Translations as $key => $values) {
            foreach (Locales::Supported as $locale) {
                Translation::query()->firstOrCreate(
                    ['locale' => $locale, 'key' => $key],
                    ['value' => $values[$locale]],
                );
            }
        }
    }
